#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sharedDataRoot = resolve(packageRoot, '..', 'shared-data');
const outputPath = resolve(packageRoot, 'src', 'catalogs', 'bundled-data.generated.ts');

const bundledPaths = [
  'banxico/banks.json',
  'sat/cfdi_4.0/c_Meses.json',
  'sat/cfdi_4.0/c_Periodicidad.json',
  'sat/cfdi_4.0/c_TasaOCuota.json',
  'sat/cfdi_4.0/c_TipoFactor.json',
  'sat/cfdi_4.0/clave_unidad.json',
  'sat/cfdi_4.0/estado.json',
  'sat/cfdi_4.0/exportacion.json',
  'sat/cfdi_4.0/forma_pago.json',
  'sat/cfdi_4.0/impuesto.json',
  'sat/cfdi_4.0/metodo_pago.json',
  'sat/cfdi_4.0/nomina_clave_prod_serv.json',
  'sat/cfdi_4.0/objeto_imp.json',
  'sat/cfdi_4.0/regimen_fiscal.json',
  'sat/cfdi_4.0/tipo_comprobante.json',
  'sat/cfdi_4.0/tipo_relacion.json',
  'sat/cfdi_4.0/uso_cfdi.json',
  'sat/nomina_1.2/banco.json',
  'sat/nomina_1.2/origen_recurso.json',
  'sat/nomina_1.2/periodicidad_pago.json',
  'sat/nomina_1.2/riesgo_puesto.json',
  'sat/nomina_1.2/tipo_contrato.json',
  'sat/nomina_1.2/tipo_deduccion.json',
  'sat/nomina_1.2/tipo_horas.json',
  'sat/nomina_1.2/tipo_incapacidad.json',
  'sat/nomina_1.2/tipo_jornada.json',
  'sat/nomina_1.2/tipo_nomina.json',
  'sat/nomina_1.2/tipo_otro_pago.json',
  'sat/nomina_1.2/tipo_percepcion.json',
  'sat/nomina_1.2/tipo_regimen.json',
  'sat/comercio_exterior/paises.json',
];

const entries = bundledPaths.map((path) => ({
  path,
  data: JSON.parse(readFileSync(resolve(sharedDataRoot, path), 'utf8')),
}));
const generated = `// Generated by scripts/generate-bundled-catalog-data.mjs. Do not edit.\n\nexport interface BundledCatalogData {\n  readonly path: string;\n  readonly data: unknown;\n}\n\nexport const BUNDLED_CATALOG_DATA: readonly BundledCatalogData[] = ${JSON.stringify(entries, null, 2)};\n`;

if (process.argv.includes('--check')) {
  const current = readFileSync(outputPath, 'utf8');
  if (current !== generated) {
    throw new Error(
      'Bundled catalog data is stale. Run npm run generate:catalog-data in packages/typescript.'
    );
  }
} else {
  writeFileSync(outputPath, generated);
}
